export interface EmojiSelection {
	start: number;
	end: number;
}

/**
 * Inserts an emoji where the caret is, replacing the current selection. Pure so the composer
 * can restore the caret itself after Vue has re-rendered the field.
 */
export function insertEmoji(
	value: string,
	emoji: string,
	selection: EmojiSelection | null,
): { value: string; caret: number } {
	const clamp = (position: number) => Math.min(Math.max(position, 0), value.length);
	const start = selection ? clamp(selection.start) : value.length;
	const end = selection ? Math.max(clamp(selection.end), start) : start;
	return {
		value: value.slice(0, start) + emoji + value.slice(end),
		caret: start + emoji.length,
	};
}
