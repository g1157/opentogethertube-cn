import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

// One source for the palette. Both the Vuetify ThemeDefinitions and the CSS custom
// properties are derived from this file, so a colour can no longer be changed in one
// place and forgotten in the other (D4).
const PALETTES_URL = new URL("../src/styles/theme-palettes.json", import.meta.url);
const OUTPUT_URL = new URL("../src/styles/_theme-vars.generated.scss", import.meta.url);
const URL_PATH_PREFIX = /^\/(?:[A-Za-z]:)?/;

const HEADER = `/* Generated from theme-palettes.json by client/scripts/generate-theme-css.mjs.
 * Do not edit this file by hand. Run \`yarn workspace ott-client run themes:generate\`.
 */
`;

// The order the interface has always declared its variables in. Keeping it stable makes
// the generated file reviewable against the hand-written blocks it replaced.
const PRE_VARS = [
	"ink",
	"primary-bright",
	"primary-deep",
	"signal",
	"signal-deep",
	"surface-2",
	"surface-3",
	"success",
	"warning",
	"glow-primary",
	"glow-signal",
	"shadow-panel",
	"text-glow-primary",
	"hero-text-glow",
	"hero-core-a",
	"hero-core-b",
	"hero-core-opacity",
	"hero-accent-a",
	"hero-accent-b",
	"hero-accent-blend",
	"hero-accent-opacity",
];

const POST_VARS = [
	"background",
	"foreground",
	"card",
	"card-foreground",
	"popover",
	"popover-foreground",
	"primary",
	"primary-foreground",
	"secondary",
	"secondary-foreground",
	"muted",
	"muted-foreground",
	"accent",
	"accent-foreground",
	"destructive",
	"destructive-foreground",
	"border",
	"input",
	"ring",
	"radius",
];

// Vuetify names the same roles differently from the shadcn-style CSS the components use.
// These pairs are resolved from the Vuetify colour map; a theme may still override one in
// `vars` when the two interfaces intentionally diverge (teal's signal is the known case).
const DERIVED = {
	"primary-bright": colors => colors["primary-lighten-1"],
	"primary-deep": colors => colors["primary-darken-1"],
	signal: colors => colors.secondary,
	background: colors => colors.background,
	foreground: colors => colors["on-background"],
	card: colors => colors.surface,
	"card-foreground": colors => colors["on-surface"],
	primary: colors => colors.primary,
	"primary-foreground": colors => colors["on-primary"],
	destructive: colors => colors.error,
	ring: colors => colors.primary,
	success: colors => colors.success,
	warning: colors => colors.warning,
};

const ALL_VARS = new Set([...PRE_VARS, ...POST_VARS]);

// Not every theme paints a hero or a glowing heading; omitted variables are simply not
// declared, exactly as the hand-written blocks did.
const OPTIONAL_VARS = new Set([
	"text-glow-primary",
	"hero-text-glow",
	"hero-core-a",
	"hero-core-b",
	"hero-core-opacity",
	"hero-accent-a",
	"hero-accent-b",
	"hero-accent-blend",
	"hero-accent-opacity",
]);

export function loadPalettes(source = readFileSync(PALETTES_URL, "utf8")) {
	const palettes = JSON.parse(source);
	assert.equal(typeof palettes, "object", "Theme palettes must be an object");
	const names = Object.keys(palettes);
	assert(names.length > 0, "No theme palettes found");
	assert.equal(names[0], "dark", "The first palette is the :root fallback and must be dark");
	return palettes;
}

/** Resolve one palette to the CSS custom properties its theme block declares. */
export function themeCssVariables(palette, name = "theme") {
	assert.equal(typeof palette.dark, "boolean", `${name}: missing boolean "dark"`);
	assert.equal(typeof palette.colors, "object", `${name}: missing "colors"`);
	const vars = palette.vars ?? {};
	assert.equal(typeof vars, "object", `${name}: "vars" must be an object`);
	for (const key of Object.keys(vars)) {
		assert(ALL_VARS.has(key), `${name}: unsupported CSS variable "${key}"`);
	}
	const colors = palette.colors;
	const resolved = {};
	for (const key of ALL_VARS) {
		const value = vars[key] ?? DERIVED[key]?.(colors);
		if (value === undefined && OPTIONAL_VARS.has(key)) {
			continue;
		}
		assert.equal(typeof value, "string", `${name}: no value for --${key}`);
		assert(value.trim().length > 0, `${name}: empty value for --${key}`);
		resolved[key] = value;
	}
	return resolved;
}

export function renderThemeCss(palettes) {
	const names = Object.keys(palettes);
	const blocks = names.map((name, index) => {
		const palette = palettes[name];
		const vars = themeCssVariables(palette, name);
		const selector = index === 0 ? `:root,\n[data-theme="${name}"]` : `[data-theme="${name}"]`;
		const lines = [selector + " {", `\tcolor-scheme: ${palette.dark ? "dark" : "light"};`];
		if (palette.note) {
			lines.push(`\t/* ${palette.note} */`);
		}
		for (const key of PRE_VARS) {
			if (key in vars) {
				lines.push(`\t--${key}: ${vars[key]};`);
			}
		}
		lines.push("");
		for (const key of POST_VARS) {
			if (key in vars) {
				lines.push(`\t--${key}: ${vars[key]};`);
			}
		}
		lines.push("}");
		return lines.join("\n");
	});
	return `${HEADER}\n${blocks.join("\n\n")}\n`;
}

function main() {
	const check = process.argv.includes("--check");
	const rendered = renderThemeCss(loadPalettes());
	if (check) {
		let current = "";
		try {
			current = readFileSync(OUTPUT_URL, "utf8");
		} catch {
			// A missing file is a stale build, reported the same way as a changed one.
		}
		if (current !== rendered) {
			process.stderr.write(
				"Theme CSS is out of date. Run: yarn workspace ott-client run themes:generate\n",
			);
			process.exitCode = 1;
		} else {
			process.stdout.write(
				`PASS: generated theme CSS matches theme-palettes.json (${
					Object.keys(loadPalettes()).length
				} themes).\n`,
			);
		}
		return;
	}
	writeFileSync(OUTPUT_URL, rendered);
	process.stdout.write(
		`Wrote ${OUTPUT_URL.pathname.replace(URL_PATH_PREFIX, "")} (${
			Object.keys(loadPalettes()).length
		} themes).\n`,
	);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
	main();
}
